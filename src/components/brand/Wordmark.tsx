interface WordmarkProps {
  /** "claro" = sobre fundo navy; "escuro" = sobre fundo claro. */
  tom?: "claro" | "escuro";
  /** Envolve a marca num link para a home. */
  comoLink?: boolean;
  tamanho?: "sm" | "md" | "lg";
  variante?: "completa" | "simbolo";
  className?: string;
}

const ALTURAS = {
  sm: "h-6",
  md: "h-7 sm:h-8",
  lg: "h-10 sm:h-12",
} as const;

export function Wordmark({
  tom = "escuro",
  comoLink = false,
  tamanho = "md",
  variante = "completa",
  className,
}: WordmarkProps) {
  const simbolo = variante === "simbolo";

  const marca = (
    <svg
      viewBox={simbolo ? "0 0 292.5 375.6" : "0 0 1136.4 379.3"}
      role="img"
      aria-label="Dullimp"
      className={cn(
        "w-auto shrink-0",
        ALTURAS[tamanho],
        tom === "claro" ? "text-white" : "text-brand-navy",
        className,
      )}
    >
      {simbolo ? (
        <path fill="currentColor" fillRule="evenodd" d={SIMBOLO_ISOLADO} />
      ) : (
        <>
          <path fill="currentColor" fillRule="evenodd" d={SIMBOLO} />
          <path fill="currentColor" fillRule="evenodd" d={LETRAS} />
        </>
      )}
    </svg>
  );

  if (!comoLink) return marca;

  return (
    <Link
      href="/"
      aria-label="Portal Dullimp — página inicial"
      className="inline-flex items-center rounded-md"
    >
      {marca}
    </Link>
  );
}
